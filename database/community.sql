CREATE TABLE IF NOT EXISTS start_links (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT NOT NULL,
 title VARCHAR(100) NOT NULL,
 target_url VARCHAR(2000) NOT NULL,
 group_name VARCHAR(50) NOT NULL DEFAULT 'Everyday',
 position INTEGER NOT NULL DEFAULT 0,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS start_notes (
 user_id BIGINT PRIMARY KEY,
 body TEXT NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS projects (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT NOT NULL,
 title VARCHAR(160) NOT NULL,
 summary TEXT NOT NULL,
 source_url VARCHAR(2000) NOT NULL DEFAULT '',
 state VARCHAR(20) NOT NULL DEFAULT 'planning',
 visibility VARCHAR(20) NOT NULL DEFAULT 'private',
 created_at VARCHAR(30) NOT NULL,
 updated_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS project_updates (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 project_id BIGINT NOT NULL,
 kind VARCHAR(20) NOT NULL,
 title VARCHAR(160) NOT NULL,
 body TEXT NOT NULL,
 cost_cents INTEGER NOT NULL DEFAULT 0,
 completed INTEGER NOT NULL DEFAULT 0,
 created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS rings (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT NOT NULL,
 name VARCHAR(100) NOT NULL,
 description TEXT NOT NULL,
 created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS ring_members (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 ring_id BIGINT NOT NULL,
 user_id BIGINT NOT NULL,
 website VARCHAR(2000) NOT NULL DEFAULT '',
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 created_at VARCHAR(30) NOT NULL,
 UNIQUE(ring_id,user_id),
 FOREIGN KEY (ring_id) REFERENCES rings(id) ON DELETE CASCADE,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS funding_reports (
 month VARCHAR(7) PRIMARY KEY,
 hosting_cents INTEGER NOT NULL,
 backups_cents INTEGER NOT NULL,
 other_cents INTEGER NOT NULL,
 contributions_cents INTEGER NOT NULL,
 notes TEXT NOT NULL,
 updated_at VARCHAR(30) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS directory_details (
 directory_id BIGINT PRIMARY KEY,
 alternatives VARCHAR(250) NOT NULL DEFAULT '',
 FOREIGN KEY (directory_id) REFERENCES directory(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS directory_facts (
 directory_id BIGINT NOT NULL,
 dimension VARCHAR(20) NOT NULL,
 description VARCHAR(500) NOT NULL,
 evidence_url VARCHAR(2000) NOT NULL,
 checked_on VARCHAR(10) NOT NULL,
 PRIMARY KEY(directory_id,dimension),
 FOREIGN KEY (directory_id) REFERENCES directory(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS directory_corrections (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 directory_id BIGINT NOT NULL,
 user_id BIGINT NOT NULL,
 body TEXT NOT NULL,
 evidence_url VARCHAR(2000) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'open',
 created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (directory_id) REFERENCES directory(id) ON DELETE CASCADE,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
